# ============================================================
# STATE DEFINITION
# ============================================================
# The ResearchState is the "shared memory" of the pipeline.
# Every agent reads from this state and writes updates back to it.
# LangGraph passes this state object between all nodes automatically.
#
# WHY TypedDict:
#   TypedDict gives us type safety -- we know exactly what fields
#   exist in the state and what types they should be. This prevents
#   bugs where an agent tries to read a field that doesn't exist.
#
# FIELD DESCRIPTIONS:
#   topic:          The user's research topic (set at the start, never changes)
#   config:         The loaded configuration dictionary (shared across all agents)
#   sub_questions:  Generated by Planner Agent, used by Search Agent
#   search_results: Generated by Search Agent, used by Summarizer Agent
#   summaries:      Generated by Summarizer Agent, used by Writer Agent
#   report:         Generated by Writer Agent, used by Critic Agent
#   review:         Generated by Critic Agent, final output
#   error:          Any error message (None if pipeline succeeded)
#   status:         Current pipeline status for UI progress tracking
# ============================================================

class ResearchState(TypedDict):
    """
    The shared state object that flows through the entire research pipeline.

    WHY THIS CLASS EXISTS:
        In LangGraph, all agents communicate through a shared state object.
        This TypedDict defines the exact schema of that state -- what data
        exists, what type it is, and what it means. Every agent reads
        from this state and returns a dictionary of updates to merge back in.

    FIELDS:
        topic (str):
            The original research topic entered by the user.
            Set once at the beginning, never modified.
            Example: "Impact of AI on Healthcare"

        config (dict):
            The loaded configuration from config.yaml.
            Shared across all agents to avoid reloading the file multiple times.
            Contains API keys, model settings, agent configs, etc.

        sub_questions (List[str]):
            Generated by the Planner Agent.
            A list of focused sub-questions derived from the topic.
            Example: ["What is AI in healthcare?", "What are AI diagnostic tools?", ...]

        search_results (Dict[str, Any]):
            Generated by the Search Agent.
            Maps each sub-question to its web + Wikipedia search results.
            Structure: {question: {web_results: [...], wikipedia: {...}, formatted_context: "..."}}

        summaries (Dict[str, str]):
            Generated by the Summarizer Agent.
            Maps each sub-question to a clean, concise summary.
            Structure: {question: "Summary text..."}

        report (str):
            Generated by the Writer Agent.
            The full research report in Markdown format.

        review (Dict[str, Any]):
            Generated by the Critic Agent.
            Contains score, grade, verdict, strengths, weaknesses, suggestions.

        error (Optional[str]):
            Set if any agent encounters a fatal error.
            None if the pipeline completed successfully.

        status (str):
            Current status message for UI progress tracking.
            Updated by each agent as it starts/completes.
    """
    topic: str
    config: dict
    sub_questions: List[str]
    search_results: Dict[str, Any]
    summaries: Dict[str, str]
    report: str
    review: Dict[str, Any]
    error: Optional[str]
    status: str


# ============================================================
# NODE FUNCTIONS
# ============================================================
# Each node function:
# 1. Receives the current state as input
# 2. Runs its agent
# 3. Returns a dictionary of state updates (only the fields it changes)
# LangGraph merges these updates into the state automatically.
# ============================================================

def planner_node(state: ResearchState) -> dict:
    """
    LangGraph node that runs the Planner Agent.

    WHY THIS FUNCTION EXISTS:
        LangGraph requires each agent to be wrapped in a "node function"
        that follows a specific signature: takes state as input, returns
        a dict of state updates. This wrapper function bridges the gap
        between LangGraph's interface and our Planner Agent's interface.

    HOW IT WORKS:
        1. Reads the topic and config from the current state
        2. Calls run_planner_agent() to generate sub-questions
        3. Returns a dict updating 'sub_questions' and 'status' in the state
        4. If an error occurs, sets the 'error' field in the state

    WHAT IT UPDATES IN STATE:
        - sub_questions: The list of generated sub-questions
        - status: Progress message for the UI

    Args:
        state (ResearchState): The current pipeline state.

    Returns:
        dict: State updates to merge into the pipeline state.
              Keys: 'sub_questions', 'status' (and 'error' if failed)
    """
    print("\n" + "="*60)
    print("AGENT 1/5: PLANNER AGENT")
    print("="*60)

    try:
        # Extract needed data from state
        topic = state["topic"]
        config = state["config"]

        # Run the Planner Agent
        sub_questions = run_planner_agent(topic=topic, config=config)

        return {
            "sub_questions": sub_questions,
            "status": f"Planner: Generated {len(sub_questions)} sub-questions"
        }

    except Exception as e:
        error_msg = f"Planner Agent failed: {str(e)}"
        print(f"ERROR: {error_msg}")
        return {
            "sub_questions": [state["topic"]],  # Fallback: use topic as single question
            "error": error_msg,
            "status": "Planner failed -- using fallback"
        }


def search_node(state: ResearchState) -> dict:
    """
    LangGraph node that runs the Search Agent.

    WHY THIS FUNCTION EXISTS:
        Wraps the Search Agent in LangGraph's node interface.
        Reads sub_questions from state (set by Planner Agent),
        runs web + Wikipedia searches, and updates search_results in state.

    HOW IT WORKS:
        1. Reads sub_questions and config from state
        2. Calls run_search_agent() to fetch web + Wikipedia results
        3. Returns a dict updating 'search_results' and 'status'

    WHAT IT UPDATES IN STATE:
        - search_results: Dict mapping questions to their search results
        - status: Progress message for the UI

    Args:
        state (ResearchState): The current pipeline state.

    Returns:
        dict: State updates with 'search_results' and 'status'.
    """
    print("\n" + "="*60)
    print("AGENT 2/5: SEARCH AGENT")
    print("="*60)

    try:
        sub_questions = state["sub_questions"]
        config = state["config"]

        # Run the Search Agent
        search_results = run_search_agent(
            sub_questions=sub_questions,
            config=config
        )

        total_web = sum(len(r.get("web_results", [])) for r in search_results.values())

        return {
            "search_results": search_results,
            "status": f"Search: Found {total_web} web results for {len(search_results)} questions"
        }

    except Exception as e:
        error_msg = f"Search Agent failed: {str(e)}"
        print(f"ERROR: {error_msg}")
        return {
            "search_results": {},
            "error": error_msg,
            "status": "Search failed"
        }


