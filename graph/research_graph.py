# ============================================================
# graph/research_graph.py
# ============================================================
# PURPOSE:
#   This module is the CENTRAL ORCHESTRATOR of the entire multi-agent
#   research pipeline. It uses LangGraph to define a state machine
#   (a directed graph) that connects all 5 agents in sequence and
#   manages the flow of data between them.
#
# WHY WE NEED A GRAPH ORCHESTRATOR:
#   Without an orchestrator, we'd have to manually call each agent
#   and pass data between them in a long, fragile script. LangGraph
#   provides a structured, visual way to define agent pipelines:
#   - Each agent is a "node" in the graph
#   - Data flows between nodes through "edges"
#   - The "state" object carries all data through the pipeline
#   - The graph handles execution order automatically
#
#   This is the industry-standard pattern for building multi-agent
#   systems in 2024-2025. LangGraph is used by companies like
#   LinkedIn, Uber, and many AI startups for production agent systems.
#
# HOW LANGGRAPH WORKS (simplified):
#   1. Define a State class (TypedDict) -- this is the shared memory
#      that all agents read from and write to
#   2. Define node functions -- each agent is wrapped in a node function
#      that reads from state and returns updates to state
#   3. Build the graph -- connect nodes with edges (START -> node1 -> node2 -> END)
#   4. Compile the graph -- LangGraph validates the structure
#   5. Run the graph -- call graph.invoke(initial_state) to execute
#
# PIPELINE FLOW:
#   START
#     |
#   [planner_node]    -> Generates sub-questions from topic
#     |
#   [search_node]     -> Fetches web + Wikipedia results
#     |
#   [summarizer_node] -> Summarizes raw results per sub-topic
#     |
#   [writer_node]     -> Writes the full research report
#     |
#   [critic_node]     -> Evaluates and scores the report
#     |
#   [save_node]       -> Saves report to disk (if enabled)
#     |
#   END
#
# TECHNOLOGY USED:
#   - LangGraph: Agent orchestration framework by LangChain
#   - TypedDict: Python type system for defining the state schema
#   - All 5 agent modules from the agents/ directory
#   - config_loader: Reads settings from config.yaml
# ============================================================

from langgraph.graph import StateGraph, START, END          # LangGraph core components
from typing import TypedDict, List, Dict, Any, Optional     # Type hints for state definition
